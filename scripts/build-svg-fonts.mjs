import { readFile, mkdir, writeFile } from "node:fs/promises";
const fonts = [
  ["Public Sans", 400, "public-sans"],
  ["Public Sans", 900, "public-sans"],
  ["Courier Prime", 400, "courier-prime"],
  ["Courier Prime", 700, "courier-prime"],
];
const rules = await Promise.all(
  fonts.map(async ([family, weight, slug]) => {
    let bytes = await readFile(
      new URL(
        `../node_modules/@fontsource/${slug}/files/${slug}-latin-${weight}-normal.woff2`,
        import.meta.url,
      ),
    );
    const woff = await readFile(
      new URL(
        `../node_modules/@fontsource/${slug}/files/${slug}-latin-${weight}-normal.woff`,
        import.meta.url,
      ),
    );
    const format = woff.length < bytes.length ? "woff" : "woff2";
    if (format === "woff") bytes = woff;
    return `@font-face{font-family:'${family}';font-style:normal;font-weight:${weight};src:url(data:font/${format};base64,${bytes.toString("base64")}) format('${format}')}`;
  }),
);
await mkdir(new URL("../src/nft", import.meta.url), { recursive: true });
await writeFile(
  new URL("../src/nft/fonts.generated.ts", import.meta.url),
  `// Generated by npm run fonts:svg from Fontsource Latin subsets.\nexport const svgFontCss=${JSON.stringify(rules.join("\n"))};\n`,
);
console.log(
  "Embedded self-hosted Latin font subsets for standalone NFT images.",
);
